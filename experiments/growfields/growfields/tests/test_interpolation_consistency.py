"""Verify consistency between the two interpolation pipelines.

Pipeline 1 — training-time (save_interpolation_from_organ_models):
    sequences/<seq>/full_plant/interpolation/predicted/pred_<seq>_D<day:02d>.ply
    sequences/<seq>/full_plant/interpolation/ground_truth/gt_<seq>_D<day:02d>.ply

Pipeline 2 — post-training script (generate_interpolation.py --n_interp 1):
    interpolation/<seq>/predicted/<seq>_D<day:.2f>_F<frame:04d>.ply
    interpolation/<seq>/ground_truth/<seq>_D<day:.2f>_F<frame:04d>.ply

With stride=2 and --n_interp 1 the single intermediate frame generated by
Pipeline 2 between each consecutive pair of training days falls at frac=0.5,
which coincides exactly with the unseen day predicted by Pipeline 1.
"""

import numpy as np
import pytest
from growfields.utils.io_utils import load_ply
from helpers import day_from_filename, day_from_filename_float
from scipy.spatial import cKDTree


def _index_by_day(files, name_fn):
    """Return {day: ply_dict} for *files*, using *name_fn* to extract the integer day."""
    result = {}
    for f in files:
        day = name_fn(f)
        if day is not None:
            result[day] = load_ply(f)
    return result


def _check_points_match(pipeline1, pipeline2, label, atol=1e-4):
    common_days = sorted(set(pipeline1) & set(pipeline2))
    assert common_days, (
        f"No common unseen days found between Pipeline 1 {sorted(pipeline1)} "
        f"and Pipeline 2 {sorted(pipeline2)}"
    )

    for day in common_days:
        pts1 = pipeline1[day]["points"]
        pts2 = pipeline2[day]["points"]
        labels1 = pipeline1[day]["organ_label"]
        labels2 = pipeline2[day]["organ_label"]

        # Pipeline 1 may include organs that first appear at the unseen day (not
        # present at either surrounding training frame), which Pipeline 2 skips.
        # Compare only organs present in both outputs.
        common_organs = sorted(set(labels1) & set(labels2))
        assert (
            common_organs
        ), f"{label} day {day}: no common organ labels between pipelines"

        for organ_id in common_organs:
            o_pts1 = pts1[labels1 == organ_id]
            o_pts2 = pts2[labels2 == organ_id]

            assert o_pts1.shape == o_pts2.shape, (
                f"{label} day {day} organ {organ_id}: point count mismatch — "
                f"Pipeline 1 has {o_pts1.shape[0]} points, Pipeline 2 has {o_pts2.shape[0]}"
            )

            # NN-match o_pts2 onto o_pts1 before comparing.
            # lexsort is fragile: float32 noise can put two near-identical points
            # on opposite sides of a rounding boundary, swapping their sort order
            # and producing a false huge mismatch.  NN gives the correct pairing
            # while assert_allclose still shows the exact mismatched coordinates.
            _, nn_idx = cKDTree(o_pts2.astype(np.float64)).query(
                o_pts1.astype(np.float64), workers=1
            )
            np.testing.assert_allclose(
                o_pts1,
                o_pts2[nn_idx],
                atol=atol,
                err_msg=f"{label} day {day} organ {organ_id}: point coordinate mismatch between pipelines",
            )


class TestInterpolationConsistency:
    """Full-plant PLYs at unseen days must match between the two pipelines."""

    def test_predicted_full_plant_points_match_between_pipelines(
        self,
        interpolation_pred_files,
        generate_interp_pred_files,
        compare_atol,
    ):
        """Predicted full-plant point clouds at unseen days must be identical.

        save_interpolation_from_organ_models (training-time) and
        generate_interpolation.py (--n_interp 1) must agree at every unseen day
        that appears in both outputs.
        """
        if not generate_interp_pred_files:
            pytest.skip(
                "generate_interpolation.py predicted output not found; run with --n_interp 1"
            )

        pipeline1 = _index_by_day(interpolation_pred_files, day_from_filename)
        pipeline2 = _index_by_day(generate_interp_pred_files, day_from_filename_float)
        _check_points_match(pipeline1, pipeline2, label="predicted", atol=compare_atol)

    def test_gt_full_plant_points_match_between_pipelines(
        self,
        interpolation_gt_files,
        generate_interp_gt_files,
        compare_atol,
    ):
        """Ground-truth full-plant point clouds at unseen days must be identical.

        Both pipelines read GT from the same dataset source, so their GT PLYs
        for the same day should contain exactly the same points regardless of
        any integration or transform differences.
        """
        if not generate_interp_gt_files:
            pytest.skip(
                "generate_interpolation.py GT output not found; run with --n_interp 1"
            )

        pipeline1 = _index_by_day(interpolation_gt_files, day_from_filename)
        pipeline2 = _index_by_day(generate_interp_gt_files, day_from_filename_float)
        _check_points_match(
            pipeline1, pipeline2, label="ground truth", atol=compare_atol
        )
